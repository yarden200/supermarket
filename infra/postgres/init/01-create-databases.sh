#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER $PRODUCT_DB_USER WITH PASSWORD '$PRODUCT_DB_PASSWORD';
    CREATE DATABASE $PRODUCT_DB_NAME OWNER $PRODUCT_DB_USER;
    REVOKE ALL ON DATABASE $PRODUCT_DB_NAME FROM PUBLIC;
    CREATE USER $ORDER_DB_USER WITH PASSWORD '$ORDER_DB_PASSWORD';
    CREATE DATABASE $ORDER_DB_NAME OWNER $ORDER_DB_USER;
    REVOKE ALL ON DATABASE $ORDER_DB_NAME FROM PUBLIC;
    CREATE USER $AUTH_DB_USER WITH PASSWORD '$AUTH_DB_PASSWORD';
    CREATE DATABASE $AUTH_DB_NAME OWNER $AUTH_DB_USER;
    REVOKE ALL ON DATABASE $AUTH_DB_NAME FROM PUBLIC;
    CREATE USER $CUSTOMER_DB_USER WITH PASSWORD '$CUSTOMER_DB_PASSWORD';
    CREATE DATABASE $CUSTOMER_DB_NAME OWNER $CUSTOMER_DB_USER;
    REVOKE ALL ON DATABASE $CUSTOMER_DB_NAME FROM PUBLIC;
EOSQL